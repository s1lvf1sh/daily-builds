'use strict';
const { chromium } = require('playwright');
const path = require('path');
const url = 'file://' + path.resolve(__dirname, '../index.html');
let pass = 0, fail = 0;
const check = (n, ok, i) => { (ok ? pass++ : fail++); console.log(`${ok ? 'ok  ' : 'FAIL'} ${n}${i ? '  ' + i : ''}`); };
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1000, height: 700 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
  await p.goto(url);
  await p.waitForTimeout(300);
  check('page loads with no errors', errs.length === 0, errs.join('; '));
  check('mode list populated', (await p.locator('#mode option').count()) >= 20);
  const m0 = await p.evaluate(() => window.__chladni.mean), base = await p.evaluate(() => window.__chladni.base);
  await p.waitForTimeout(4000);
  const m1 = await p.evaluate(() => window.__chladni.mean), steps = await p.evaluate(() => window.__chladni.steps);
  check('sand settles in the real page (mean |u| falls below 50% of start)', m1 < 0.5 * m0, `${m0.toFixed(3)} -> ${m1.toFixed(3)} after ${steps} steps; baseline ${base.toFixed(3)}`);
  await p.screenshot({ path: path.resolve(__dirname, 'screenshot.png') });
  await p.uncheck('#run'); const s1 = await p.evaluate(() => window.__chladni.steps); await p.waitForTimeout(300);
  check('unchecking Shaking stops the simulation', s1 === (await p.evaluate(() => window.__chladni.steps)));
  await p.check('#run');
  await p.evaluate(() => window.__chladni.setMode(3, 4)); await p.waitForTimeout(3000);
  check('selecting another mode re-sprinkles and settles', (await p.evaluate(() => window.__chladni.mean)) < 0.6 * (await p.evaluate(() => window.__chladni.base)) + 0.15);
  const px = await p.evaluate(() => { const c = document.getElementById('cv'), d = c.getContext('2d').getImageData(0, 0, 480, 480).data; let sand = 0; for (let i = 0; i < d.length; i += 4) if (d[i] > 180 && d[i+1] > 150) sand++; return sand; });
  check('canvas contains drawn sand pixels', px > 2000, `${px} bright pixels`);
  await p.setViewportSize({ width: 380, height: 800 }); await p.waitForTimeout(200);
  check('no horizontal scroll at phone width', await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await p.screenshot({ path: path.resolve(__dirname, 'screenshot-phone.png') });
  await b.close();
  console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
})();
